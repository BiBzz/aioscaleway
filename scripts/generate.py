def snake(name: str) -> str:
    name = re.sub(r"[^0-9A-Za-z]+", "_", name)
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return re.sub(r"_+", "_", name).strip("_").lower()


def pascal(name: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", name)
    return "".join(part[:1].upper() + part[1:] for part in parts if part)


def identifier(name: str, reserved: set[str] | frozenset[str] = frozenset()) -> str:
    result = snake(name) or "value"
    if result[0].isdigit():
        result = f"v{result}"
    if keyword.iskeyword(result) or keyword.issoftkeyword(result) or result in reserved:
        result += "_"
    return result


def product_class(product: str) -> str:
    return re.sub(r"(?<=\d)[a-z]", lambda m: m.group(0).upper(), pascal(product))


def version_class(version: str) -> str:
    return re.sub(
        r"(alpha|beta)", lambda m: m.group(1).capitalize(), version.capitalize()
    )


def docstring(*parts: str | None, indent: str) -> str:
    text = "\n\n".join(part.strip() for part in parts if part and part.strip())
    if not text:
        return ""
    text = text.translate(DASHES).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines: list[str] = []
    for paragraph in text.split("\n"):
        lead = paragraph[: len(paragraph) - len(paragraph.lstrip(" "))]
        wrapped = textwrap.wrap(
            paragraph.lstrip(" "),
            88 - len(indent),
            initial_indent=lead,
            subsequent_indent=lead + ("    " if lead else ""),
            break_long_words=False,
        )
        lines.extend(wrapped or [""])
    body = "\n".join(f"{indent}{line}" if line else "" for line in lines)
    if body.rstrip().endswith('"'):
        body += " "
    return f'{indent}"""\n{body}\n{indent}"""\n'


@dataclass
class Enumeration:
    name: str
    values: list[str]
    description: str | None


@dataclass
class ModelField:
    name: str
    wire: str
    annotation: str
    default: str | None
    description: str | None


@dataclass
class Model:
    name: str
    fields: list[ModelField]
    description: str | None


@dataclass
class Param:
    name: str
    wire: str
    location: str
    annotation: str
    required: bool
    description: str | None
    special: str | None = None


@dataclass
class Operation:
    method_name: str
    http_method: str
    path: str
    summary: str | None
    description: str | None
    deprecated: bool
    params: list[Param]
    has_body: bool
    raw_body: bool
    response: str | None
    owner_group: tuple[str, str] | None
    pagination: tuple[str, str, str, bool] | None = None


@dataclass
class ApiClass:
    name: str
    title: str
    operations: list[Operation] = field(default_factory=list)


@dataclass
class Module:
    product: str
    version: str
    enums: dict[str, Enumeration] = field(default_factory=dict)
    models: dict[str, Model] = field(default_factory=dict)
    aliases: dict[str, str] = field(default_factory=dict)
    apis: list[ApiClass] = field(default_factory=list)
    names: dict[str, str] = field(default_factory=dict)
    schemas: dict[str, Any] = field(default_factory=dict)
    building: set[str] = field(default_factory=set)
    uses: set[str] = field(default_factory=set)


class Generator:
    def __init__(self, module: Module) -> None:
        self.module = module

    def class_name(self, schema_name: str) -> str:
        if schema_name in self.module.names:
            return self.module.names[schema_name]
        parts = schema_name.split(".")
        while len(parts) > 1 and parts[0][:1].islower():
            parts = parts[1:]
        candidate = pascal("_".join(parts))
        taken = set(self.module.names.values())
        if candidate in taken or candidate in {"Money", "ScalewayModel"}:
            prefix = schema_name.split(".")
            scope = [part for part in prefix if part[:1].islower()]
            candidate = pascal(scope[-1]) + candidate if scope else candidate
        index = 2
        unique = candidate
        while unique in taken:
            unique = f"{candidate}{index}"
            index += 1
        self.module.names[schema_name] = unique
        return unique

    def ref(self, ref: str) -> str:
        schema_name = ref.rsplit("/", 1)[-1]
        if schema_name == "google.type.Money":
            self.module.uses.add("Money")
            return "Money"
        name = self.class_name(schema_name)
        if (
            name not in self.module.models
            and name not in self.module.enums
            and name not in self.module.aliases
            and schema_name not in self.module.building
        ):
            self.module.building.add(schema_name)
            self.define(name, self.module.schemas[schema_name])
            self.module.building.discard(schema_name)
        return name

    def define(self, name: str, schema: dict[str, Any]) -> None:
        if "enum" in schema and not schema.get("properties"):
            self.module.enums[name] = Enumeration(
                name,
                [str(value) for value in schema["enum"]],
                schema.get("description"),
            )
        elif self.is_object(schema) and not self.is_map(schema):
            self.module.models[name] = Model(name, [], schema.get("description"))
            self.module.models[name].fields = self.fields(name, schema)
        else:
            self.module.aliases[name] = self.annotation(schema, name)

    @staticmethod
    def types(schema: dict[str, Any]) -> list[str]:
        declared = schema.get("type")
        if declared is None:
            return []
        return declared if isinstance(declared, list) else [declared]

    def is_object(self, schema: dict[str, Any]) -> bool:
        return "object" in self.types(schema) or (
            "properties" in schema and not self.types(schema)
        )

    @staticmethod
    def is_map(schema: dict[str, Any]) -> bool:
        properties = schema.get("properties") or {}
        return bool(properties) and all(key.startswith("<") for key in properties)

    @staticmethod
    def nullable(schema: dict[str, Any]) -> bool:
        if schema.get("nullable"):
            return True
        declared = schema.get("type")
        if isinstance(declared, list) and "null" in declared:
            return True
        return any(
            alt.get("type") == "null"
            for alt in schema.get("oneOf", []) + schema.get("anyOf", [])
        )

    def annotation(self, schema: dict[str, Any], context: str) -> str:
        if not schema:
            return "Any"
        if "$ref" in schema:
            return self.ref(schema["$ref"])
        for combiner in ("oneOf", "anyOf"):
            if combiner in schema:
                alternatives = [
                    alt for alt in schema[combiner] if alt.get("type") != "null" and alt
                ]
                if not alternatives:
                    return "Any"
                if all(set(alt) <= {"required"} for alt in alternatives):
                    break
                options = [
                    self.annotation(alt, f"{context}Option{index + 1}")
                    for index, alt in enumerate(alternatives)
                ]
                return " | ".join(dict.fromkeys(options))
        if "allOf" in schema:
            parts = [alt for alt in schema["allOf"] if alt]
            if len(parts) == 1:
                return self.annotation(parts[0], context)
            merged: dict[str, Any] = {
                "type": "object",
                "properties": {},
                "required": [],
            }
            for part in parts:
                resolved = self.resolve(part)
                merged["properties"].update(resolved.get("properties") or {})
                merged["required"] += resolved.get("required") or []
            return self.inline_model(merged, context)
        if "const" in schema:
            return f"Literal[{schema['const']!r}]"
        types = [kind for kind in self.types(schema) if kind != "null"]
        if len(types) > 1:
            return " | ".join(
                self.annotation({**schema, "type": kind}, context) for kind in types
            )
        kind = types[0] if types else ("object" if "properties" in schema else None)
        if "enum" in schema and kind in (None, "string"):
            if context not in self.module.enums:
                self.module.enums[context] = Enumeration(
                    context,
                    [str(value) for value in schema["enum"]],
                    schema.get("description"),
                )
            return context
        if kind == "string":
            if schema.get("format") == "date-time":
                self.module.uses.add("datetime")
                return "datetime"
            if schema.get("format") == "binary":
                return "bytes"
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            items = schema.get("items") or {}
            return f"list[{self.annotation(items, f'{context}Item')}]"
        if kind == "object":
            if self.is_map(schema):
                value = next(iter(schema["properties"].values()))
                return f"dict[str, {self.annotation(value, f'{context}Value')}]"
            if schema.get("properties"):
                return self.inline_model(schema, context)
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"dict[str, {self.annotation(extra, f'{context}Value')}]"
            return "dict[str, Any]"
        return "Any"

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in schema:
            schema = self.module.schemas[schema["$ref"].rsplit("/", 1)[-1]]
        return schema

    def inline_model(self, schema: dict[str, Any], context: str) -> str:
        name = context
        if name not in self.module.models:
            self.module.models[name] = Model(name, [], schema.get("description"))
            self.module.models[name].fields = self.fields(name, schema)
        return name

    def fields(self, model_name: str, schema: dict[str, Any]) -> list[ModelField]:
        required = set(schema.get("required") or [])
        result: dict[str, ModelField] = {}
        for raw_wire, prop in (schema.get("properties") or {}).items():
            wire = raw_wire.replace(ZERO_WIDTH_SPACE, "")
            name = identifier(wire, RESERVED_FIELD_NAMES)
            annotation = self.annotation(prop, model_name + pascal(wire))
            default = self.default(prop, annotation, wire in required)
            if name in result:
                previous = result[name]
                options = previous.annotation.removesuffix(" | None").split(" | ")
                options += annotation.removesuffix(" | None").split(" | ")
                annotation = " | ".join(dict.fromkeys(options))
                default = None if previous.default is None else "None"
                description = previous.description
            else:
                description = prop.get("description")
            if (
                default == "None"
                and not annotation.endswith("| None")
                and annotation != "Any"
            ):
                annotation += " | None"
            result[name] = ModelField(name, wire, annotation, default, description)
        return list(result.values())

    def default(
        self, schema: dict[str, Any], annotation: str, required: bool
    ) -> str | None:
        if required:
            return None
        if self.nullable(schema) or annotation == "Any" or " | " in annotation:
            return "None"
        if annotation == "str":
            return '""'
        if annotation in ("int", "float"):
            return "0"
        if annotation == "bool":
            return "False"
        if annotation.startswith("list["):
            return "Field(default_factory=list)"
        if annotation.startswith("dict["):
            return "Field(default_factory=dict)"
        enum = self.module.enums.get(annotation)
        if enum is not None:
            unknown = next(
                (value for value in enum.values if value.startswith("unknown")), None
            )
            if unknown is not None:
                return f"{annotation}({unknown!r})"
        return "None"


def member_names(values: list[str]) -> list[str]:
    names: list[str] = []
    for value in values:
        name = re.sub(r"[^0-9A-Za-z]+", "_", value).strip("_").upper() or "EMPTY"
        if name[0].isdigit():
            name = f"_{name}"
        if keyword.iskeyword(name.lower()) and name.lower() == name:
            name += "_"
        candidate, index = name, 2
        while candidate in names:
            candidate = f"{name}_{index}"
            index += 1
        names.append(candidate)
    return names


def json_body_schema(operation: dict[str, Any]) -> dict[str, Any] | None:
    content = (operation.get("requestBody") or {}).get("content") or {}
    for media, value in content.items():
        if "json" in media:
            return value.get("schema") or {}
    return None


def response_schema(operation: dict[str, Any]) -> dict[str, Any] | None:
    for status in ("200", "201", "202"):
        content = (operation.get("responses", {}).get(status) or {}).get(
            "content"
        ) or {}
        for media, value in content.items():
            if "json" in media:
                return value.get("schema") or {}
    return None


def build_operation(
    generator: Generator, path: str, http_method: str, operation: dict[str, Any]
) -> Operation:
    method_name = identifier(operation["operationId"], RESERVED_METHOD_NAMES)
    context = pascal(operation["operationId"])
    params: list[Param] = []
    seen: set[str] = set()

    def add(param: Param) -> None:
        while param.name in seen:
            param.name += "_"
        seen.add(param.name)
        params.append(param)

    for parameter in operation.get("parameters", []):
        wire = parameter["name"]
        location = parameter["in"]
        schema = parameter.get("schema") or {}
        special = wire if location == "path" and wire in ("region", "zone") else None
        annotation = (
            "str"
            if special
            else generator.annotation(schema, context + "Request" + pascal(wire))
        )
        add(
            Param(
                identifier(wire),
                wire,
                location,
                annotation,
                bool(parameter.get("required")) or location == "path",
                parameter.get("description"),
                special,
            )
        )

    body = json_body_schema(operation)
    owner_group: tuple[str, str] | None = None
    if body is not None:
        resolved = generator.resolve(body)
        required = set(resolved.get("required") or [])
        groups = [
            set(alt.get("required") or [])
            for alt in resolved.get("oneOf", [])
            if set(alt) <= {"required"}
        ]
        properties = resolved.get("properties") or {}
        for pair in OWNER_FIELDS:
            if not all(name in properties for name in pair):
                continue
            one_of = {properties[name].get("x-one-of") for name in pair}
            if any(group & set(pair) for group in groups) or (
                len(one_of) == 1 and None not in one_of
            ):
                owner_group = pair
        for wire, prop in properties.items():
            special = None
            if wire in OWNER_KINDS:
                special = "owner" if owner_group else OWNER_KINDS[wire]
            elif wire in ("region", "zone") and any(p.wire == wire for p in params):
                continue
            add(
                Param(
                    identifier(wire),
                    wire,
                    "body",
                    generator.annotation(prop, context + "Request" + pascal(wire)),
                    wire in required and special is None,
                    prop.get("description"),
                    special,
                )
            )
    raw_body = body is None and bool(operation.get("requestBody"))
    if raw_body:
        add(Param("content", "content", "content", "bytes", True, "Raw request body."))

    response = response_schema(operation)
    response_annotation = (
        None
        if response is None
        else generator.annotation(response, context + "Response")
    )
    result = Operation(
        method_name=method_name,
        http_method=http_method.upper(),
        path=path,
        summary=operation.get("summary"),
        description=operation.get("description"),
        deprecated=bool(operation.get("deprecated")),
        params=params,
        has_body=body is not None,
        raw_body=raw_body,
        response=response_annotation,
        owner_group=owner_group,
    )
    result.pagination = pagination(generator, result, response)
    return result


def pagination(
    generator: Generator, operation: Operation, response: dict[str, Any] | None
) -> tuple[str, str, str, bool] | None:
    query = {param.wire for param in operation.params if param.location == "query"}
    if operation.http_method != "GET" or "page" not in query or response is None:
        return None
    resolved = generator.resolve(response)
    properties = resolved.get("properties") or {}
    arrays = [
        wire
        for wire, prop in properties.items()
        if "array" in generator.types(generator.resolve(prop))
    ]
    if not arrays:
        return None
    if len(arrays) > 1:
        named = [wire for wire in arrays if wire in operation.method_name]
        if len(named) != 1:
            return None
        arrays = named
    model = generator.module.models.get(operation.response or "")
    if model is None:
        return None
    item_field = next(f for f in model.fields if f.wire == arrays[0])
    item = item_field.annotation.removesuffix(" | None")
    if not item.startswith("list["):
        return None
    total_field = next((f.name for f in model.fields if f.wire == "total_count"), "")
    return item_field.name, item[5:-1], total_field, not total_field


def load_modules() -> dict[
    tuple[str, str], tuple[Module, list[tuple[str, dict[str, Any]]]]
]:
    modules: dict[tuple[str, str], tuple[Module, list[tuple[str, dict[str, Any]]]]] = {}
    for spec_path in sorted(SPECS.glob("scaleway.*.yml")):
        _, product, version, api = spec_path.stem.split(".")
        product = SDK_PRODUCT_NAMES.get(product, product)
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        key = (product, version)
        if key not in modules:
            modules[key] = (Module(product, version), [])
        module, specs = modules[key]
        for name, schema in (spec.get("components") or {}).get("schemas", {}).items():
            module.schemas.setdefault(name, schema)
        specs.append((api, spec))
    return modules


def build(module: Module, specs: list[tuple[str, dict[str, Any]]]) -> None:
    generator = Generator(module)
    for api, spec in specs:
        sub = api.removesuffix("Api")
        name = f"{product_class(module.product)}{version_class(module.version)}{sub}API"
        api_class = ApiClass(name, spec.get("info", {}).get("title", name))
        for path, item in spec.get("paths", {}).items():
            for http_method in HTTP_METHODS:
                if http_method in item:
                    api_class.operations.append(
                        build_operation(generator, path, http_method, item[http_method])
                    )
        names = [operation.method_name for operation in api_class.operations]
        duplicates = {name for name in names if names.count(name) > 1}
        if duplicates:
            raise SystemExit(f"{name}: duplicate method names {sorted(duplicates)}")
        module.apis.append(api_class)


def render_models(module: Module) -> str:
    out = [GENERATED_MARKER, "from __future__ import annotations", ""]
    if "datetime" in module.uses:
        out.append("from datetime import datetime")
    out.append("from typing import Any, Literal")
    out += ["", "from pydantic import Field", ""]
    out.append("from aioscaleway._enums import OpenStrEnum")
    core = ["ScalewayModel"] + (["Money"] if "Money" in module.uses else [])
    out.append(f"from aioscaleway._models import {', '.join(core)}")
    out.append("")
    for enum in sorted(module.enums.values(), key=lambda e: e.name):
        out += ["", f"class {enum.name}(OpenStrEnum):"]
        doc = docstring(enum.description, indent="    ")
        if doc:
            out.append(doc.rstrip("\n"))
        for member, value in zip(member_names(enum.values), enum.values, strict=True):
            out.append(f"    {member} = {value!r}")
        out.append("")
    for name, annotation in sorted(module.aliases.items()):
        out += [f"type {name} = {annotation}", ""]
    for model in sorted(module.models.values(), key=lambda m: m.name):
        out += ["", f"class {model.name}(ScalewayModel):"]
        doc = docstring(model.description, indent="    ")
        if doc:
            out.append(doc.rstrip("\n"))
        if not model.fields:
            out.append("    pass")
        for item in model.fields:
            arguments = []
            if item.default is not None and item.default.startswith("Field("):
                arguments.append(item.default[6:-1])
            elif item.default is not None:
                arguments.append(f"default={item.default}")
            if item.name != item.wire:
                arguments.append(f"alias={item.wire!r}")
            if arguments and (
                item.name != item.wire
                or item.default
                and item.default.startswith("Field(")
            ):
                value = f" = Field({', '.join(arguments)})"
            elif item.default is not None:
                value = f" = {item.default}"
            else:
                value = ""
            out.append(f"    {item.name}: {item.annotation}{value}")
            doc = docstring(item.description, indent="    ")
            if doc:
                out.append(doc.rstrip("\n"))
        out.append("")
    return "\n".join(out) + "\n"


def signature(operation: Operation) -> list[str]:
    lines = ["self", "*"]
    ordered = sorted(
        operation.params, key=lambda p: not p.required or p.special is not None
    )
    for param in ordered:
        if param.required and param.special is None:
            lines.append(f"{param.name}: {param.annotation}")
        else:
            annotation = param.annotation
            if not annotation.endswith("| None") and annotation != "Any":
                annotation += " | None"
            lines.append(f"{param.name}: {annotation} = None")
    return lines if len(lines) > 2 else ["self"]


def request_call(operation: Operation, page: bool = False) -> list[str]:
    path_values = []
    for param in operation.params:
        if param.location != "path":
            continue
        if param.special == "region":
            value = "self._client.region(region)"
        elif param.special == "zone":
            value = "self._client.zone(zone)"
        else:
            value = param.name
        path_values.append(f"{param.wire}={value}")
    if path_values:
        path = f"self._client.path({operation.path!r}, {', '.join(path_values)})"
    else:
        path = repr(operation.path)
    arguments = [repr(operation.http_method), path]
    query = [
        f"{param.wire!r}: {'page' if page and param.wire == 'page' else param.name}"
        for param in operation.params
        if param.location == "query"
    ]
    if query:
        arguments.append("params={" + ", ".join(query) + "}")
    if operation.has_body:
        entries = []
        for param in operation.params:
            if param.location != "body" or param.special == "owner":
                continue
            if param.special in OWNER_KINDS.values():
                entries.append(
                    f"{param.wire!r}: self._client.{param.special}({param.name})"
                )
            else:
                entries.append(f"{param.wire!r}: {param.name}")
        body = "{" + ", ".join(entries) + "}"
        if operation.owner_group:
            project, organization = operation.owner_group
            owner = (
                f"**self._client.owner(project_id={identifier(project)}, "
                f"organization_id={identifier(organization)}, "
                f"keys=({project!r}, {organization!r}))"
            )
            body = "{" + ", ".join(entries + [owner]) + "}"
        arguments.append(f"body={body}")
    if operation.raw_body:
        arguments.append("content=content")
    return arguments


def render_operation(operation: Operation) -> list[str]:
    params = signature(operation)
    returns = operation.response or "None"
    out = [f"    async def {operation.method_name}("]
    out += [f"        {item}," for item in params]
    out.append(f"    ) -> {returns}:")
    notes = "Deprecated by Scaleway." if operation.deprecated else None
    args = "\n".join(
        f"    {param.name}: {' '.join((param.description or '').split())}"
        for param in operation.params
        if param.description
    )
    doc = docstring(
        operation.summary,
        operation.description if operation.description != operation.summary else None,
        notes,
        f"Args:\n{args}" if args else None,
        indent="        ",
    )
    if doc:
        out.append(doc.rstrip("\n"))
    call = ", ".join(request_call(operation))
    if operation.response is None:
        out.append(f"        await self._client.request({call})")
    else:
        out.append(f"        data = await self._client.request_json({call})")
        out.append(
            f"        return TypeAdapter({returns}).validate_python(data)"
            if not is_model(operation.response)
            else f"        return {returns}.model_validate(data)"
        )
    out.append("")
    if operation.pagination is not None:
        out += render_pagination(operation)
    return out


def is_model(annotation: str) -> bool:
    return bool(re.fullmatch(r"[A-Z][A-Za-z0-9]*", annotation)) and annotation != "Any"


def render_pagination(operation: Operation) -> list[str]:
    assert operation.pagination is not None and operation.response is not None
    items_field, item, total_field, header_total = operation.pagination
    params = [p for p in signature(operation) if not p.startswith("page:")]
    out = [f"    async def {operation.method_name}_iter("]
    out += [f"        {entry}," for entry in params]
    out.append(f"    ) -> AsyncIterator[{item}]:")
    name = operation.method_name
    out.append(f'        """Iterate over every item of `{name}`, page after page."""')
    page_type = f"tuple[{operation.response}, int | None]"
    out.append(f"        async def fetch(page: int) -> {page_type}:")
    call = ", ".join(request_call(operation, page=True))
    out.append(f"            response = await self._client.request({call})")
    out.append(
        f"            result = {operation.response}.model_validate(response.json())"
    )
    if header_total:
        out.append('            header = response.headers.get("x-total-count")')
        out.append("            return result, int(header) if header else None")
    else:
        out.append(f"            return result, result.{total_field}")
    out.append("")
    out.append("        async for entry in paginate(")
    out.append("            fetch,")
    out.append(f"            lambda page: page[0].{items_field} or [],")
    out.append("            lambda page: page[1],")
    out.append("        ):")
    out.append("            yield entry")
    out.append("")
    out.append(f"    async def {operation.method_name}_all(")
    out += [f"        {entry}," for entry in params]
    out.append(f"    ) -> list[{item}]:")
    out.append(
        f'        """Every item of `{operation.method_name}`, all pages read."""'
    )
    forwarded = [
        f"{entry.split(':')[0]}={entry.split(':')[0]}"
        for entry in params
        if entry not in ("self", "*")
    ]
    iterator = f"self.{operation.method_name}_iter({', '.join(forwarded)})"
    out.append(f"        return [entry async for entry in {iterator}]")
    out.append("")
    return out


def render_api(module: Module) -> str:
    out = [GENERATED_MARKER, "from __future__ import annotations", ""]
    out.append("from collections.abc import AsyncIterator")
    if "datetime" in module.uses:
        out.append("from datetime import datetime")
    out.append("from typing import Any, Literal")
    out += ["", "from pydantic import TypeAdapter", ""]
    out.append("from aioscaleway._client import ScalewayClient, paginate")
    if "Money" in module.uses:
        out.append("from aioscaleway._models import Money")
    names = sorted(set(module.models) | set(module.enums) | set(module.aliases))
    if names:
        out.append(
            f"from aioscaleway.{module.product}.{module.version}.models import ("
        )
        out += [f"    {name}," for name in names]
        out.append(")")
    out.append("")
    for api in module.apis:
        out += ["", f"class {api.name}:"]
        out.append(docstring(api.title, indent="    ").rstrip("\n"))
        out += [
            "",
            "    def __init__(self, client: ScalewayClient) -> None:",
            "        self._client = client",
            "",
        ]
        for operation in api.operations:
            out += render_operation(operation)
    return "\n".join(out) + "\n"


def render_init(module: Module) -> str:
    names = sorted(
        {api.name for api in module.apis}
        | set(module.models)
        | set(module.enums)
        | set(module.aliases)
    )
    out = [GENERATED_MARKER]
    out.append(f"from aioscaleway.{module.product}.{module.version}.api import (")
    out += [f"    {api.name}," for api in sorted(module.apis, key=lambda a: a.name)]
    out.append(")")
    data_names = sorted(set(module.models) | set(module.enums) | set(module.aliases))
    if data_names:
        out.append(
            f"from aioscaleway.{module.product}.{module.version}.models import ("
        )
        out += [f"    {name}," for name in data_names]
        out.append(")")
    out.append("")
    out.append("__all__ = [")
    out += [f"    {name!r}," for name in names]
    out.append("]")
    return "\n".join(out) + "\n"


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def clean() -> None:
    for init in PACKAGE.glob("*/__init__.py"):
        if init.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            shutil.rmtree(init.parent)


def main(
    format_code: bool = typer.Option(True, help="Run ruff on the output."),
) -> None:
    clean()
    modules = load_modules()
    products: dict[str, list[str]] = defaultdict(list)
    for (product, version), (module, specs) in sorted(modules.items()):
        build(module, specs)
        base = PACKAGE / product / version
        write(base / "models.py", render_models(module))
        write(base / "api.py", render_api(module))
        write(base / "__init__.py", render_init(module))
        products[product].append(version)
        operations = sum(len(api.operations) for api in module.apis)
        typer.echo(
            f"{product}.{version}: {operations} operations, {len(module.models)} models"
        )
    for product in products:
        write(PACKAGE / product / "__init__.py", GENERATED_MARKER + "\n")
    if format_code:
        targets = [str(PACKAGE / product) for product in products]
        subprocess.run(["ruff", "check", "--fix", "--quiet", *targets], check=False)
        subprocess.run(["ruff", "format", "--quiet", *targets], check=True)


if __name__ == "__main__":
    typer.run(main)
